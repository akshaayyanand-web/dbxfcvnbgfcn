"""Scientific report content built only from stored records.

A report is a structured document (sections with paragraphs, key-value tables, data
tables and figures) assembled from: the experiment record, its latest completed
analysis, stored predictions, the model card, dataset provenance and the scientific
assumptions register. Text is generated from those values with fixed wording; no
statement goes beyond what the records contain, and predictions are never described
as measurements or discoveries.
"""

from __future__ import annotations

import math
from datetime import datetime, timezone
from typing import Any

SECTIONS = [
    ("overview", "Experiment overview"),
    ("conditions", "Experimental conditions"),
    ("provenance", "Dataset provenance"),
    ("video", "Video specifications"),
    ("calibration", "Calibration"),
    ("cv_methodology", "Computer-vision methodology"),
    ("measurements", "Flame measurements"),
    ("temporal", "Temporal analysis"),
    ("model", "Predictive model"),
    ("model_evaluation", "Model evaluation"),
    ("uncertainty", "Uncertainty"),
    ("limitations", "Scientific limitations"),
    ("conclusions", "Conclusions"),
]
SECTION_IDS = [s for s, _ in SECTIONS]


def _f(x: Any, digits: int = 2, unit: str = "") -> str:
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "not available"
    if isinstance(x, (int, float)):
        return f"{x:.{digits}f}{(' ' + unit) if unit else ''}"
    return str(x)


def _stat(summary: dict | None, key: str) -> dict:
    return (summary or {}).get(key) or {}


def _series(measurements: list[dict], ykey: str) -> list[list[float]]:
    return [[m["timestamp_s"], m[ykey]] for m in measurements if m.get(ykey) is not None and m.get("timestamp_s") is not None]


def build_experiment_report(exp: dict, analysis: dict | None, predictions: list[dict], model: dict | None,
                            sections: list[str]) -> dict:
    """Return ``{"title", "generated_at", "sections": [{"id","title","blocks":[...]}]}``."""
    wanted = [s for s in SECTION_IDS if s in sections] or SECTION_IDS
    summary = (analysis or {}).get("summary") or {}
    video = (analysis or {}).get("video") or {}
    cal = (analysis or {}).get("calibration") or exp.get("calibration")
    cfg = (analysis or {}).get("config") or exp.get("analysis_config") or {}
    meas = (analysis or {}).get("measurements") or []
    method = summary.get("radius_method", cfg.get("radius_method", "equivalent"))
    rkey = "limb_radius_mm" if method == "limb" else "radius_mm"
    out: list[dict] = []

    def add(sid: str, blocks: list[dict]) -> None:
        if sid in wanted:
            out.append({"id": sid, "title": dict(SECTIONS)[sid], "blocks": blocks})

    data_class = exp.get("data_class", "user")
    class_note = {"synthetic": "SYNTHETIC demonstration data generated by the platform; not an experiment.",
                  "nasa_psi": "NASA ACME s-Flame data from the Physical Sciences Informatics system (PSI-23, CC0-1.0).",
                  "user": "Data supplied by the user."}.get(data_class, data_class)
    add("overview", [
        {"type": "kv", "rows": [["Experiment", exp.get("name")], ["Experiment ID", exp.get("id")],
                                ["Data class", class_note], ["Status", exp.get("status")],
                                ["Created", exp.get("created_at")], ["Latest analysis job", exp.get("latest_job_id") or "none"]]},
        {"type": "p", "text": exp.get("description") or "No description recorded."},
    ])
    add("conditions", [{"type": "kv", "rows": [
        ["Fuel", exp.get("fuel_type") or "not recorded"],
        ["Oxygen (mole fraction)", _f(exp.get("oxygen_fraction"), 3)],
        ["Chamber pressure", _f(exp.get("chamber_pressure_kpa"), 1, "kPa")],
        ["Planned burn duration", _f(exp.get("burn_duration_s"), 1, "s")],
        ["Dataset reference", exp.get("dataset_ref") or "none"],
    ]}, {"type": "p", "text": "Conditions are as entered or as taken from the source record; nominal values are not "
                              "corrected for gas conversion factors (SCIENTIFIC_ASSUMPTIONS A-SF-4)."}])
    add("provenance", [{"type": "p", "text": class_note + (
        " Source files and checksums are listed in data/processed/sflame_manifest.json; the investigation DOI is "
        "10.60555/k57n-p030." if data_class == "nasa_psi" else "")}])
    if analysis:
        add("video", [{"type": "kv", "rows": [
            ["Input", video.get("filename")], ["Container / codec", f"{video.get('container')} / {video.get('codec_name') or video.get('codec_fourcc')}"],
            ["Resolution", f"{video.get('width')} × {video.get('height')} px"], ["Nominal frame rate", _f(video.get("nominal_fps"), 3, "fps")],
            ["Frames (reported)", video.get("reported_frame_count")], ["Duration", _f(video.get("duration_s"), 2, "s")],
            ["Timestamp source", summary.get("timestamp_source")], ["Decoder", summary.get("decoder")],
        ]}])
    else:
        add("video", [{"type": "p", "text": "No completed analysis; video specifications unavailable."}])
    if cal:
        add("calibration", [{"type": "kv", "rows": [
            ["Method", cal.get("method")], ["Reference length", _f(cal.get("known_length_mm"), 3, "mm")],
            ["Measured length", f"{_f(cal.get('measured_length_px'), 2, 'px')} ± {_f(cal.get('measured_length_sigma_px'), 2, 'px')}"],
            ["Scale", f"{_f(cal.get('mm_per_px'), 5, 'mm/px')} ± {_f(cal.get('mm_per_px_sigma'), 5)}"],
            ["Camera", cal.get("camera_id") or "not recorded"], ["Notes", cal.get("notes") or ""],
        ]}])
    else:
        add("calibration", [{"type": "p", "text": "No calibration: all lengths are in pixels and no physical units are reported."}])
    seg = cfg.get("segmentation") or {}
    add("cv_methodology", [
        {"type": "kv", "rows": [["Segmentation", f"{seg.get('method', 'otsu')} on the {seg.get('channel', 'max')} channel"],
                                ["Gaussian blur / morphology", f"{seg.get('blur_kernel', 5)} px / {seg.get('morph_kernel', 5)} px"],
                                ["Minimum contour area", _f(seg.get("min_contour_area_px"), 0, "px²")],
                                ["Radius method", "shell-limb circle fit (A-CV-14)" if method == "limb" else "area-equivalent radius (A-CV-2)"],
                                ["Derivatives", f"local polynomial, window {(cfg.get('derivatives') or {}).get('window', 7)}, order {(cfg.get('derivatives') or {}).get('polyorder', 2)}, in actual timestamps (A-PH-2)"],
                                ["Frame step / processing scale", f"{cfg.get('frame_step', 1)} / {cfg.get('processing_scale', 1.0)}"]]},
        {"type": "p", "text": "Frames without an accepted detection are left empty and never interpolated (A-CV-7)."},
    ])
    if analysis:
        r = _stat(summary, "limb_radius_mm" if method == "limb" else "radius_mm") or _stat(summary, "equivalent_radius_px")
        unit = "mm" if _stat(summary, "limb_radius_mm" if method == "limb" else "radius_mm") else "px"
        v = _stat(summary, "expansion_velocity_mm_s") or _stat(summary, "expansion_velocity_px_s")
        vunit = "mm/s" if _stat(summary, "expansion_velocity_mm_s") else "px/s"
        ext = summary.get("extinction") or {}
        counts = summary.get("status_counts") or {}
        vols = [m["equivalent_volume_mm3"] for m in meas if m.get("equivalent_volume_mm3") is not None]
        add("measurements", [
            {"type": "kv", "rows": [
                ["Frames analysed", summary.get("frames_analyzed")], ["Detected", counts.get("detected")],
                ["Limb fits accepted" if method == "limb" else "Low confidence", summary.get("limb_fits_ok") if method == "limb" else counts.get("low_confidence")],
                ["Radius range", f"{_f(r.get('min'))} – {_f(r.get('max'))} {unit}"], ["Radius mean", f"{_f(r.get('mean'))} {unit}"],
                ["Max equivalent spherical volume (estimate)", _f(max(vols), 0, "mm³") if vols else "not reported (non-spherical or uncalibrated)"],
                ["Peak expansion rate", f"{_f(v.get('max'), 3)} {vunit}" if v else "not available"],
                ["Visible extinction", f"{_f(ext.get('time_s'), 3, 's')} ± {_f(ext.get('uncertainty_s'), 3, 's')} ({ext.get('status')})"],
            ]},
            {"type": "p", "text": "Measured and calculated quantities are image-derived from a 2-D projection. The equivalent "
                                  "spherical volume is a model estimate, not a 3-D measurement (A-PH-1)."},
        ])
        add("temporal", [
            {"type": "figure", "id": "radius", "title": f"Flame radius vs time ({unit})", "x": "t (s)", "y": f"radius ({unit})",
             "series": [{"name": "radius", "class": "image_derived", "points": _series(meas, rkey if unit == "mm" else "equivalent_radius_px")}]},
            {"type": "figure", "id": "velocity", "title": f"Radial expansion rate ({vunit})", "x": "t (s)", "y": vunit,
             "series": [{"name": "dr/dt", "class": "calculated", "points": _series(meas, "expansion_velocity_mm_s" if vunit == "mm/s" else "expansion_velocity_px_s")}]},
        ])
    else:
        add("measurements", [{"type": "p", "text": "No completed analysis for this experiment."}])
        add("temporal", [{"type": "p", "text": "No completed analysis for this experiment."}])

    if model:
        add("model", [{"type": "kv", "rows": [
            ["Model version", model.get("model_version")], ["Population", model.get("population")],
            ["Target", (model.get("target") or {}).get("definition")], ["Distribution", model.get("distribution")],
            ["Training data", f"{(model.get('training_data') or {}).get('n')} tests, {(model.get('training_data') or {}).get('n_events')} observed extinctions"],
            ["Features", ", ".join(f["name"] for f in model.get("features", []))],
        ]}])
        sel = (model.get("validation") or {}).get("selected") or {}
        add("model_evaluation", [{"type": "kv", "rows": [
            ["Validation", (model.get("validation") or {}).get("scheme")],
            ["C-index across held-out days", _f(sel.get("c_index"), 3)], ["C-index within day", _f(sel.get("c_index_within_day"), 3)],
            ["Median |log error| (events)", _f(sel.get("events_median_abs_log_error"), 3)],
            ["Baseline median |log error|", _f(((model.get("validation") or {}).get("baseline_intercept_only") or {}).get("events_median_abs_log_error"), 3)],
        ]}, {"type": "p", "text": "The model ranks test conditions better than chance but does not predict absolute "
                                  "lifetimes on new test days better than the baseline (A-ML-4)."}])
    else:
        add("model", [{"type": "p", "text": "No predictive model is loaded."}])
        add("model_evaluation", [{"type": "p", "text": "No predictive model is loaded."}])

    unc = [["Radius (median 1σ)", "from stored per-frame uncertainties" if meas else "not available"]]
    if meas:
        sig = sorted(m.get("limb_radius_sigma_mm") if method == "limb" else m.get("radius_sigma_mm") for m in meas
                     if (m.get("limb_radius_sigma_mm") if method == "limb" else m.get("radius_sigma_mm")) is not None)
        unc = [["Radius 1σ (median over frames)", _f(sig[len(sig) // 2], 3, "mm") if sig else "not available"],
               ["Included", "boundary localisation and calibration scale (A-UQ-1)"],
               ["Not included", "segmentation-method offset, line-of-sight effects, non-sphericity (A-UQ-3)"]]
    pblocks: list[dict] = [{"type": "kv", "rows": unc}]
    if predictions:
        rows = []
        for p in predictions[:10]:
            res = p.get("result") or {}
            iv = res.get("interval") or {}
            rows.append([p.get("created_at", "")[:19], p.get("model_version"), _f(res.get("median_lifetime_s"), 2, "s"),
                         f"{_f(iv.get('lower_s'), 2)} – {_f(iv.get('upper_s'), 2)} s ({int(100 * (iv.get('level') or 0))} %)",
                         "; ".join(res.get("warnings") or []) or "none"])
        pblocks.append({"type": "table", "title": "Predictions for this experiment (predicted, not measured)",
                        "columns": ["Run", "Model", "Median lifetime", "Interval", "Warnings"], "rows": rows})
    add("uncertainty", pblocks)
    lim = ["Measurements come from a 2-D projection of a 3-D flame.",
           "The reported uncertainty is a lower bound on the total error (A-UQ-3)."]
    if data_class == "synthetic":
        lim.insert(0, "This report describes SYNTHETIC data and makes no statement about real flames.")
    if summary.get("frames_volume_suppressed_non_spherical"):
        lim.append(f"Equivalent volume suppressed in {summary['frames_volume_suppressed_non_spherical']} frames because the flame was not circular.")
    for i in (analysis or {}).get("issues") or []:
        if i.get("severity") in ("warning", "error"):
            lim.append(f"{i.get('code')}: {i.get('message')}")
    if model:
        lim.extend(model.get("limitations", [])[:4])
    add("limitations", [{"type": "list", "items": lim}])

    concl: list[str] = []
    if analysis:
        r = _stat(summary, rkey) if unit == "mm" else _stat(summary, "equivalent_radius_px")
        if r:
            concl.append(f"The {('shell-limb' if method == 'limb' else 'area-equivalent')} flame radius ranged from "
                         f"{_f(r.get('min'))} to {_f(r.get('max'))} {unit} over {_f(summary.get('analysed_time_span_s'), 2)} s of analysed video.")
        ext = summary.get("extinction") or {}
        if ext.get("status") == "observed":
            concl.append(f"Visible emission ended at {_f(ext.get('time_s'), 3)} ± {_f(ext.get('uncertainty_s'), 3)} s after the first analysed frame.")
        else:
            concl.append(f"Extinction was not observed in the analysed frames ({ext.get('status')}).")
    if predictions:
        concl.append("Predictions listed above are model outputs with intervals; they are not experimental confirmations.")
    if not concl:
        concl.append("No analysis or prediction results are available yet, so no conclusions are drawn.")
    add("conclusions", [{"type": "list", "items": concl}])

    return {"schema": "flame-in-freefall/report/v1", "title": f"Analysis report: {exp.get('name')}",
            "experiment_id": exp.get("id"), "generated_at": datetime.now(timezone.utc).isoformat(), "sections": out}


def build_comparison_report(items: list[tuple[dict, dict | None]]) -> dict:
    """Comparison of several experiments: conditions table, key-result table and overlaid radius curves."""
    cond_rows, res_rows, series = [], [], []
    for exp, analysis in items:
        s = (analysis or {}).get("summary") or {}
        method = s.get("radius_method", "equivalent")
        key = "limb_radius_mm" if method == "limb" else "radius_mm"
        r = s.get(key) or {}
        ext = s.get("extinction") or {}
        cond_rows.append([exp.get("id"), exp.get("name"), exp.get("fuel_type") or "—", _f(exp.get("oxygen_fraction"), 3),
                          _f(exp.get("chamber_pressure_kpa"), 1), exp.get("data_class")])
        res_rows.append([exp.get("id"), method, _f(r.get("max")), _f(r.get("mean")),
                         _f((s.get("expansion_velocity_mm_s") or {}).get("max"), 3),
                         _f(ext.get("time_s"), 3) if ext.get("status") == "observed" else "not observed"])
        meas = (analysis or {}).get("measurements") or []
        series.append({"name": exp.get("id"), "class": "image_derived", "points": _series(meas, key)})
    return {"schema": "flame-in-freefall/report/v1", "title": "Comparison report: " + ", ".join(e.get("id") for e, _ in items),
            "generated_at": datetime.now(timezone.utc).isoformat(), "sections": [
                {"id": "conditions", "title": "Experimental conditions", "blocks": [{"type": "table", "columns": [
                    "ID", "Name", "Fuel", "O₂ (mole fr.)", "Pressure (kPa)", "Data class"], "rows": cond_rows}]},
                {"id": "measurements", "title": "Flame behaviour", "blocks": [{"type": "table", "columns": [
                    "ID", "Radius method", "Max radius (mm)", "Mean radius (mm)", "Peak dr/dt (mm/s)", "Extinction (s)"], "rows": res_rows},
                    {"type": "p", "text": "Times are relative to each experiment's first analysed frame; radii from different "
                                          "radius methods are not interchangeable (A-CV-3)."}]},
                {"id": "temporal", "title": "Radius vs time", "blocks": [{"type": "figure", "id": "compare", "title": "Flame radius (mm)",
                                                                          "x": "t (s)", "y": "radius (mm)", "series": series}]},
                {"id": "limitations", "title": "Scientific limitations", "blocks": [{"type": "list", "items": [
                    "Differences are descriptive; experiments differ in more than the listed conditions (A-SF-7).",
                    "Synthetic experiments, if included, are not physical data."]}]},
            ]}
